    local listName, listOwner, listMembers, listClaims, listExtra =
        text:match("^(.+) owner=(.+) members=(%d+) claims=%[(.*)%](.*)$")
    if listName then
        local attacker, held, need = listExtra:match(" RAID<%-(.+) hold=(%d+)/(%d+)$")
        if attacker then
            listExtra = translated("UI_LFS_ReportRaidSuffix",
                " RAID<-%s hold=%s/%s", attacker, held, need)
        end
        return translated("UI_LFS_ReportFactionList", text,
            listName, listOwner, listMembers, listClaims, listExtra)
    end
    local zoneId, zoneSource, zoneGeometry, zoneName =
        text:match("^(%S+) %[([^%]]+)%] (.-) %-%- (.+)$")
    if zoneId and (zoneSource == "admin" or zoneSource == "zone" or zoneSource == "?") then
        if zoneSource == "admin" then zoneSource = translated("UI_LFS_ReportSourceAdmin", "admin")
        elseif zoneSource == "zone" then zoneSource = translated("UI_LFS_ReportSourceZone", "zone") end
        zoneGeometry = zoneGeometry:gsub("no geometry",
            translated("UI_LFS_ReportNoGeometry", "no geometry"))
        local more = zoneGeometry:match(" %+(%d+) more$")
        if more then
            zoneGeometry = zoneGeometry:gsub(" %+(%d+) more$",
                translated("UI_LFS_ReportMoreAreas", " +%s more", more))
        end
        return translated("UI_LFS_ReportNoClaimLine", text,
            zoneId, zoneSource, zoneGeometry, zoneName)
    end
    for _, entry in ipairs(DYNAMIC_PATTERNS) do
        local captures = { text:match(entry[2]) }
        if captures[1] ~= nil then
            return translated(entry[1], text, unpack(captures))
        end
    end
    return text
end
