function FF.tr(text, ...)
    if type(text) ~= "string" then return text end
    local key = KEYS[text]
    if key then return translated(key, text, ...) end
    local value = text:match("^Invited to (.+)$")
    if value then return translated("UI_LFS_DynamicInvitedTo", text, value) end
    value = text:match("^Under attack by (.+)$")
    if value then return translated("UI_LFS_DynamicUnderAttack", text, value) end
    value = text:match("^Raiding (.+)$")
    if value then return translated("UI_LFS_DynamicRaiding", text, value) end
    value = text:match("^(%d+) online now$")
    if value then return translated("UI_LFS_DynamicOnline", text, value) end
    value = text:match("^Territory (%d+)%% used$")
    if value then return translated("UI_LFS_DynamicTerritoryUsed", text, value) end
    local a, b = text:match("^(%d+) / (%d+) tiles$")
    if a then return translated("UI_LFS_DynamicTiles", text, a, b) end
    local w, h, area = text:match("^Area (%d+) x (%d+) %((%d+) tiles%)$")
    if w then return translated("UI_LFS_DynamicArea", text, w, h, area) end
    value = text:match("^(.+) pts$")
    if value then return translated("UI_LFS_DynamicPoints", text, value) end
    value = text:match("^(.+) tiles$")
    if value then return translated("UI_LFS_DynamicTileCount", text, value) end
    value = text:match("^(%d+) members$")
    if value then return translated("UI_LFS_DynamicMembers", text, value) end
    if text == "1 member" then return translated("UI_LFS_DynamicMemberOne", text) end
    value = text:match("^War %-%- vs (.+)$")
    if value then return translated("UI_LFS_DynamicWarVs", text, value) end
    value = text:match("^first to (%d+)$")
    if value then return translated("UI_LFS_DynamicFirstTo", text, value) end
    value = text:match("^vs (.+)$")
    if value then return translated("UI_LFS_DynamicVs", text, value) end
    value = text:match("^allies: (.+)$")
    if value then return translated("UI_LFS_DynamicAllies", text, value) end
    local d, hr = text:match("^(%d+)d (%d+)h$")
    if d then return translated("UI_LFS_DynamicDaysHours", text, d, hr) end
    local won, lost, defended = text:match("^(%d+) raids won%s+%-%s+(%d+) lost%s+%-%s+(%d+) defended$")
    if won then return translated("UI_LFS_DynamicRaidRecord", text, won, lost, defended) end
    local attacker, defender = text:match("^(.+) attacking (.+)$")
    if attacker then return translated("UI_LFS_DynamicAttacking", text, attacker, defender) end
    local applicants = text:match("^Applicants%s+(%d+)$")
    if applicants then return translated("UI_LFS_DynamicApplicants", text, applicants) end
    local browsing = text:match("^Browsing%s+(%d+)$")
    if browsing then return translated("UI_LFS_DynamicBrowsing", text, browsing) end
    value = text:match("^ROLE: (.+)$")
    if value then return translated("UI_LFS_DynamicRole", text, value) end
    local pactA, pactB, pactDetail = text:match("^(.+) <%-> (.+) %((.+)%)$")
    if pactA then
        local detail = pactDetail
        detail = detail:gsub("indefinite", translated("UI_LFS_Indefinite", "indefinite"))
        local hours = detail:match("^(%d+)h left")
        if hours then
            detail = detail:gsub("^%d+h left", translated("UI_LFS_ReportHoursLeft", "%s h left", hours))
        end
        local shared = pactDetail:match("; shares (.+)$")
        if shared then
            local terms = shared:gsub("map", translated("UI_LFS_MapTerm", "map"))
                :gsub("locations", translated("UI_LFS_LocationsTerm", "locations"))
            local prefix = translated("UI_LFS_ReportShares", "; shares %s", terms)
